/** Curriculum topics + lesson builders for grades 5–9 */

function lesson(opts) {
  return JSON.stringify({
    goals: opts.goals || [],
    theory: opts.theory || '',
    rules: opts.rules || [],
    terms: opts.terms || [],
    examples: opts.examples || [],
    tables: opts.tables || [],
    texts: opts.texts || [],
    practice: opts.practice || [],
    selfcheck: opts.selfcheck || [],
    summary: opts.summary || '',
    homework: opts.homework || []
  });
}

function t(question, type, options, correct, explanation, level) {
  return {
    question,
    type,
    options_json: options != null ? JSON.stringify(options) : null,
    correct_json: JSON.stringify(correct),
    explanation,
    level: level || 'easy'
  };
}

